// Writes the phone page's generated assets under pkg/remotemode/web/static from the cockpit's
// single sources, so the page never carries a second copy of the palette, fonts or icon:
//   tokens.css  every --color-* and --font-* declaration of the @theme block in frontend/tailwindsetup.css
//   fonts/      the Hanken Grotesk and JetBrains Mono woff2 files from public/fonts
//   icon.png    the 256 px frame of src-tauri/icons/icon.ico
//   projectors.js  the cockpit's claude and pi transcript projectors, bundled by esbuild (a
//               transitive dependency through vite) from frontend/app/view/agents/remoteprojectors.ts
//   markdown.js the cockpit's markdown parser (mdast-util-from-markdown with GFM, under remark-gfm),
//               bundled the same way from frontend/app/view/agents/remotemarkdown.ts
// The outputs are committed (go build must work in a fresh tree) and never hand-edited.
//
// Usage (from the repo root): node scripts/sync-remote-web.mjs
// Wired as task sync:remoteweb, a dep wherever sync:piartifacts is one.

import { buildSync } from "esbuild";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const PROJECTORS_ENTRY = "frontend/app/view/agents/remoteprojectors.ts";
const PROJECTORS_OUT = "pkg/remotemode/web/static/projectors.js";
const MARKDOWN_ENTRY = "frontend/app/view/agents/remotemarkdown.ts";
const MARKDOWN_OUT = "pkg/remotemode/web/static/markdown.js";
const CSS_PATH = "frontend/tailwindsetup.css";
const ICO_PATH = "src-tauri/icons/icon.ico";
const OUT_DIR = "pkg/remotemode/web/static";
const FONTS = [
    "hanken-grotesk-variable.woff2",
    "jetbrains-mono-v13-latin-regular.woff2",
    "jetbrains-mono-v13-latin-700.woff2",
];
const ICON_SIZE = 256;
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

function writeTokens() {
    const css = readFileSync(CSS_PATH, "utf8");
    const themeBlock = css.match(/@theme \{([\s\S]*?)\n\}/);
    if (!themeBlock) {
        throw new Error(`${CSS_PATH}: no @theme block found`);
    }
    const decls = themeBlock[1]
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .split(";")
        // a value may span lines (rgba(...) and the font stacks); fold it onto one
        .map((d) => d.trim().replace(/\s+/g, " ").replace(/\( /g, "(").replace(/ \)/g, ")"))
        .filter((d) => d.startsWith("--color-") || d.startsWith("--font-"));
    if (!decls.length) {
        throw new Error(`${CSS_PATH}: no --color-* or --font-* declarations in @theme`);
    }
    const out = [
        `/* generated by scripts/sync-remote-web.mjs from ${CSS_PATH}; never hand-edit */`,
        ":root {",
        ...decls.map((d) => `    ${d};`),
        "}",
        "",
    ].join("\n");
    writeFileSync(`${OUT_DIR}/tokens.css`, out);
    return decls.length;
}

function copyFonts() {
    mkdirSync(`${OUT_DIR}/fonts`, { recursive: true });
    for (const f of FONTS) {
        copyFileSync(`public/fonts/${f}`, `${OUT_DIR}/fonts/${f}`);
    }
}

// An ICO is a 6-byte header (reserved, type, count) and a 16-byte entry per frame: width and height
// bytes (0 means 256), then at byte 8 the frame's size and at byte 12 its offset.
function writeIcon() {
    const ico = readFileSync(ICO_PATH);
    const count = ico.readUInt16LE(4);
    let icon = null;
    for (let i = 0; i < count; i++) {
        const entry = 6 + 16 * i;
        const width = ico[entry] || 256;
        const size = ico.readUInt32LE(entry + 8);
        const offset = ico.readUInt32LE(entry + 12);
        const frame = ico.subarray(offset, offset + size);
        if (!frame.subarray(0, PNG_SIGNATURE.length).equals(PNG_SIGNATURE)) {
            throw new Error(`${ICO_PATH}: frame ${i} (${width} px) is not PNG-encoded`);
        }
        if (width === ICON_SIZE) {
            icon = frame;
        }
    }
    if (!icon) {
        throw new Error(`${ICO_PATH}: no ${ICON_SIZE} px frame`);
    }
    writeFileSync(`${OUT_DIR}/icon.png`, icon);
}

// absWorkingDir pins the path comments esbuild writes into the output, so a bundle does not depend on
// the caller's cwd.
function bundleBuildOptions(entry, outfile) {
    return {
        absWorkingDir: ROOT,
        entryPoints: [entry],
        outfile,
        bundle: true,
        format: "esm",
        platform: "browser",
        banner: { js: `/* generated by scripts/sync-remote-web.mjs from ${entry}; never hand-edit */` },
        logLevel: "warning",
    };
}

// exported so the bundles' freshness tests rebuild with the same options
export const projectorsBuildOptions = () => bundleBuildOptions(PROJECTORS_ENTRY, PROJECTORS_OUT);
// the "worker" condition picks decode-named-character-reference's table build over its browser one,
// which decodes an entity by writing it into an element's innerHTML (and needs a DOM in the tests)
export const markdownBuildOptions = () => ({
    ...bundleBuildOptions(MARKDOWN_ENTRY, MARKDOWN_OUT),
    conditions: ["worker"],
});

// importing this file (the freshness test does) must not write anything
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const n = writeTokens();
    copyFonts();
    writeIcon();
    buildSync(projectorsBuildOptions());
    buildSync(markdownBuildOptions());
    console.log(`ok: ${OUT_DIR}: tokens.css (${n} declarations), ${FONTS.length} fonts, icon.png, projectors.js, markdown.js`);
}
