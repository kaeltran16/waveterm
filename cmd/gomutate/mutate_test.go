const fixtureGoMod = "module fixture\n\ngo 1.21\n"

// fixture builds a git module whose base commit holds baseFiles and whose HEAD adds headFiles on top.
// It returns the tree and the base sha.
func fixture(t *testing.T, baseFiles, headFiles map[string]string) (string, string) {
	t.Helper()
	dir := t.TempDir()
	git(t, dir, "init", "-q")
	writeFiles(t, dir, map[string]string{"go.mod": fixtureGoMod})
	writeFiles(t, dir, baseFiles)
	commit(t, dir, "base")
	base := strings.TrimSpace(git(t, dir, "rev-parse", "HEAD"))
	writeFiles(t, dir, headFiles)
	commit(t, dir, "head")
	return dir, base
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for rel, content := range files {
		p := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func commit(t *testing.T, dir, msg string) {
	t.Helper()
	git(t, dir, "add", "-A")
	git(t, dir, "-c", "user.name=t", "-c", "user.email=t@t", "commit", "-q", "--allow-empty", "-m", msg)
}

func git(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", dir, "-c", "core.autocrlf=false"}, args...)...)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return string(out)
}

func run(t *testing.T, cfg Config) Report {
	t.Helper()
	if cfg.Max == 0 {
		cfg.Max = 200
	}
	if cfg.Timeout == 0 {
		cfg.Timeout = 60 * time.Second
	}
	cfg.Progress = io.Discard
	rep, err := Run(cfg)
	if err != nil {
		t.Fatalf("Run: %v", err)
	}
	return rep
}

func TestAssertedLineKilledUnassertedSurvives(t *testing.T) {
	t.Parallel()
	dir, base := fixture(t, map[string]string{
		"calc/calc.go": "package calc\n",
	}, map[string]string{
		"calc/calc.go": "package calc\n" +
			"\n" +
			"func Add(a, b int) int { return a + b }\n" + // line 3
			"\n" +
			"func Small(x int) bool { return x < 10 }\n", // line 5
		"calc/calc_test.go": "package calc\n" +
			"\n" +
			"import \"testing\"\n" +
			"\n" +
			"func TestAdd(t *testing.T) {\n" +
			"\tif Add(2, 3) != 5 {\n" +
			"\t\tt.Fatal(\"add\")\n" +
			"\t}\n" +
			"}\n",
	})
	rep := run(t, Config{Dir: dir, Base: base})

	if rep.Killed != 1 || rep.Survived != 1 || rep.TimedOut != 0 || rep.Invalid != 0 {
		t.Fatalf("counts = killed %d survived %d timedOut %d invalid %d, want 1/1/0/0",
			rep.Killed, rep.Survived, rep.TimedOut, rep.Invalid)
	}
	want := []Survivor{{Path: "calc/calc.go", Line: 5, Op: "< to <="}}
	if !reflect.DeepEqual(rep.Survivors, want) {
		t.Fatalf("survivors = %+v, want %+v", rep.Survivors, want)
	}
	if rep.Score == nil || *rep.Score != 0.5 {
		t.Fatalf("score = %v, want 0.5", rep.Score)
	}
	wantFiles := []FileCounts{{Path: "calc/calc.go", Killed: 1, Survived: 1}}
	if !reflect.DeepEqual(rep.Files, wantFiles) {
		t.Fatalf("files = %+v, want %+v", rep.Files, wantFiles)
	}
	if rep.Tool != "gomutate" || rep.Base != base {
		t.Fatalf("tool/base = %q/%q", rep.Tool, rep.Base)
	}
	head := strings.TrimSpace(git(t, dir, "rev-parse", "HEAD"))
	if rep.Head != head {
		t.Fatalf("head = %q, want %q", rep.Head, head)
	}
}

func TestOnlyDiffLinesOfNonTestNonGeneratedFiles(t *testing.T) {
	t.Parallel()
	dir, base := fixture(t, map[string]string{
		"lib/old.go": "package lib\n" +
			"\n" +
			"func Old(a, b int) bool { return a < b && a != 0 }\n",
	}, map[string]string{
		"lib/old.go": "package lib\n" +
			"\n" +
			"func Old(a, b int) bool { return a < b && a != 0 }\n" +
			"\n" +
			"func New(a int) bool { return a > 0 }\n", // line 5: the only mutable change
		"lib/gen.go": "// Code generated by fixture. DO NOT EDIT.\n" +
			"\n" +
			"package lib\n" +
			"\n" +
			"func Gen(a int) bool { return a <= 1 || true }\n",
		"lib/lib_test.go": "package lib\n" +
			"\n" +
			"import \"testing\"\n" +
			"\n" +
			"func TestNothing(t *testing.T) {\n" +
			"\tif 1+1 == 3 && false {\n" +
			"\t\tt.Fatal(\"x\")\n" +
			"\t}\n" +
			"}\n",
		"lib/testdata/data.go": "package data\n\nfunc D(a int) bool { return a > 1 }\n",
	})
	rep := run(t, Config{Dir: dir, Base: base})

	want := []Survivor{{Path: "lib/old.go", Line: 5, Op: "> to >="}}
	if !reflect.DeepEqual(rep.Survivors, want) {
		t.Fatalf("survivors = %+v, want %+v", rep.Survivors, want)
	}
	if rep.Killed+rep.TimedOut+rep.Invalid != 0 {
		t.Fatalf("unexpected mutants: %+v", rep)
	}
}

