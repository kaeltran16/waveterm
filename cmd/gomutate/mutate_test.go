func TestTimeoutCountsAsTimedOut(t *testing.T) {
	t.Parallel()
	dir, base := fixture(t, map[string]string{
		"loop/loop.go": "package loop\n" +
			"\n" +
			"func Count(n int) int {\n" +
			"\tc := 0\n" +
			"\tfor i := 0; i < n; i = i + step() {\n" +
			"\t\tc++\n" +
			"\t}\n" +
			"\treturn c\n" +
			"}\n" +
			"\n" +
			"func step() int { return 1 }\n",
		"loop/loop_test.go": "package loop\n" +
			"\n" +
			"import \"testing\"\n" +
			"\n" +
			"func TestCount(t *testing.T) {\n" +
			"\tif Count(3) != 3 {\n" +
			"\t\tt.Fatal(\"count\")\n" +
			"\t}\n" +
			"}\n",
	}, map[string]string{
		// 0 + 1 mutates to 0 - 1, which makes Count loop forever
		"loop/step.go": "package loop\n\nfunc other() int { return 0 + 1 }\n",
		"loop/loop.go": "package loop\n" +
			"\n" +
			"func Count(n int) int {\n" +
			"\tc := 0\n" +
			"\tfor i := 0; i < n; i = i + step() {\n" +
			"\t\tc++\n" +
			"\t}\n" +
			"\treturn c\n" +
			"}\n" +
			"\n" +
			"func step() int { return other() }\n",
	})
	rep := run(t, Config{Dir: dir, Base: base, Timeout: 5 * time.Second})
	if rep.TimedOut != 1 || rep.Killed+rep.Survived+rep.Invalid != 0 {
		t.Fatalf("counts = %+v, want one timedOut", rep)
	}
	if rep.Score == nil || *rep.Score != 1 {
		t.Fatalf("score = %v, want 1", rep.Score)
	}
}

func TestTreeUntouchedAndSeedPicksSameSample(t *testing.T) {
	t.Parallel()
	var src strings.Builder
	src.WriteString("package m\n\n")
	for _, f := range []string{"A", "B", "C", "D", "E", "F"} {
		fmt.Fprintf(&src, "func %s(x int) bool { return x > 1 }\n", f)
	}
	dir, base := fixture(t, map[string]string{"m/m.go": "package m\n"}, map[string]string{"m/m.go": src.String()})
	before := snapshot(t, dir)

	first := run(t, Config{Dir: dir, Base: base, Max: 3, Seed: 7})
	second := run(t, Config{Dir: dir, Base: base, Max: 3, Seed: 7})

	if len(first.Survivors) != 3 {
		t.Fatalf("sample size = %d, want 3", len(first.Survivors))
	}
	if !reflect.DeepEqual(first.Survivors, second.Survivors) {
		t.Fatalf("same seed, different sample: %+v vs %+v", first.Survivors, second.Survivors)
	}
	if after := snapshot(t, dir); !reflect.DeepEqual(before, after) {
		t.Fatal("tree files changed during the run")
	}
}

// snapshot reads every working-tree file outside .git.
func snapshot(t *testing.T, dir string) map[string]string {
	t.Helper()
	files := map[string]string{}
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if d.Name() == ".git" {
				return filepath.SkipDir
			}
			return nil
		}
		b, err := os.ReadFile(p)
		files[p] = string(b)
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return files
}
